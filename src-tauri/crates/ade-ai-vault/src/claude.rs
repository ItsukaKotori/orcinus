pub fn scan_claude_sessions(projects_root: &Path, limit: usize) -> (Vec<Value>, Vec<ScanIssue>) {
    let (rows, issues, _) = scan_claude_sessions_cancellable(projects_root, limit, None);
    (rows, issues)
}

/// Cancellable scan body. The flag is checked before each transcript so a
/// superseded scan stops walking the project tree instead of parsing the rest
/// of it; a cancelled scan returns whatever it folded plus `true`.
pub(crate) fn scan_claude_sessions_cancellable(
    projects_root: &Path,
    limit: usize,
    cancel: Option<&CancelFlag>,
) -> (Vec<Value>, Vec<ScanIssue>, bool) {
    let mut files = Vec::new();
    let mut issues = Vec::new();
    collect_session_files(projects_root, &mut files, &mut issues);

    let mut rows = Vec::new();
    for path in files {
        if cancel.is_some_and(CancelFlag::is_cancelled) {
            return (rows, issues, true);
        }
        match read_session_row(&path) {
            Ok(row) => rows.push(row),
            Err(message) => issues.push(ScanIssue {
                agent: "claude".to_string(),
                kind: "scope".to_string(),
                path: path.to_string_lossy().into_owned(),
                message,
            }),
        }
    }

    rows.sort_by(|left, right| {
        let left = effective_recency(left);
        let right = effective_recency(right);
        right.cmp(left)
    });
    rows.truncate(limit);
    (rows, issues, false)
}

pub(crate) fn effective_recency(row: &Value) -> &str {
    row["updatedAt"]
        .as_str()
        .filter(|value| !value.is_empty())
        .or_else(|| row["modifiedAt"].as_str().filter(|value| !value.is_empty()))
        .unwrap_or("")
}

fn collect_session_files(dir: &Path, files: &mut Vec<PathBuf>, issues: &mut Vec<ScanIssue>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(error) => {
            if error.kind() != std::io::ErrorKind::NotFound {
                issues.push(ScanIssue {
                    agent: "claude".to_string(),
                    kind: "scope".to_string(),
                    path: dir.to_string_lossy().into_owned(),
                    message: error.to_string(),
                });
            }
            return;
        }
    };
    let mut entries: Vec<_> = entries.filter_map(Result::ok).collect();
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let path = entry.path();
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if file_type.is_dir() {
            let name = entry.file_name();
            let name = name.to_string_lossy();
            if PRUNED_DIR_NAMES
                .iter()
                .any(|pruned| name.as_ref() == *pruned)
            {
                continue;
            }
            collect_session_files(&path, files, issues);
        } else if file_type.is_file() && has_jsonl_extension(&path) {
            files.push(path);
        }
    }
}

pub(crate) fn has_jsonl_extension(path: &Path) -> bool {
    path.extension()
        .is_some_and(|extension| extension.to_string_lossy().eq_ignore_ascii_case("jsonl"))
}

/// The title this transcript names, without the scanner's generated fallback:
/// custom-title > latest ai-title > first non-injected user text > agent-name.
/// `None` when the file cannot be read or names no title at all.
pub fn read_claude_title(path: &Path) -> Option<String> {
    let bytes = fs::read(path).ok()?;
    let content = String::from_utf8_lossy(&bytes);
    let fold = fold_session(&content, session_id_from_file_name(path));
    extracted_title(&fold)
}

fn read_session_row(path: &Path) -> Result<Value, String> {
    let metadata = fs::metadata(path).map_err(|error| error.to_string())?;
    let modified_at = metadata
        .modified()
        .map(system_time_to_iso)
        .map_err(|error| error.to_string())?;
    let bytes = fs::read(path).map_err(|error| error.to_string())?;
    let content = String::from_utf8_lossy(&bytes);
    let fold = fold_session(&content, session_id_from_file_name(path));
    Ok(build_row(path, &modified_at, fold))
}

struct PreviewMessage {
    role: &'static str,
    text: String,
    timestamp: Option<String>,
}

struct SessionFold {
    session_id: String,
    custom_title: Option<String>,
    ai_title: Option<String>,
    first_user_title: Option<String>,
    meta_title: Option<String>,
    cwd: Option<String>,
    branch: Option<String>,
    model: Option<String>,
    created_at: Option<(i64, String)>,
    updated_at: Option<(i64, String)>,
    latest_timestamp_ms: i64,
    message_count: u64,
    total_tokens: u64,
    preview_messages: Vec<PreviewMessage>,
    preview_messages_truncated: bool,
    queued_message_count: u64,
    last_user_prompt: Option<String>,
}

fn fold_session(content: &str, session_id: String) -> SessionFold {
    let mut fold = SessionFold {
        session_id,
        custom_title: None,
        ai_title: None,
        first_user_title: None,
        meta_title: None,
        cwd: None,
        branch: None,
        model: None,
        created_at: None,
        updated_at: None,
        latest_timestamp_ms: 0,
        message_count: 0,
        total_tokens: 0,
        preview_messages: Vec::new(),
        preview_messages_truncated: false,
        queued_message_count: 0,
        last_user_prompt: None,
    };

    for line in content.lines() {
        let Ok(value) = serde_json::from_str::<Value>(line) else {
            continue;
        };
        let Some(record) = value.as_object() else {
            continue;
        };

        if let Some(id) = extract_string(record.get("sessionId")) {
            fold.session_id = id.to_string();
        }
        update_timeline(&mut fold, record.get("timestamp"));
        update_location(&mut fold, record);

        match record.get("type").and_then(Value::as_str) {
            Some("custom-title") => {
                fold.custom_title =
                    normalize_title_text(extract_string(record.get("customTitle")).unwrap_or(""));
            }
            Some("ai-title") => {
                if let Some(title) =
                    normalize_title_text(extract_string(record.get("aiTitle")).unwrap_or(""))
                {
                    fold.ai_title = Some(title);
                }
            }
            Some("agent-name") => {
                if fold.ai_title.is_none() && fold.meta_title.is_none() {
                    fold.meta_title =
                        normalize_title_text(extract_string(record.get("agentName")).unwrap_or(""));
                }
            }
            Some("last-prompt") => {
                if let Some(prompt) =
                    normalize_content_text(record.get("lastPrompt"), PREVIEW_TEXT_LIMIT)
                {
                    fold.last_user_prompt = Some(prompt);
                }
            }
            Some("queue-operation") => match record.get("operation").and_then(Value::as_str) {
                Some("enqueue") => {
                    if extract_string(record.get("content")).is_some() {
                        fold.queued_message_count += 1;
                    }
                }
                Some("remove") | Some("dequeue") => {
                    fold.queued_message_count = fold.queued_message_count.saturating_sub(1);
                }
                _ => {}
            },
            Some("user") => {
                fold.message_count += 1;
                let title = extract_message_text(record.get("message"));
                let is_meta = record
                    .get("isMeta")
                    .and_then(Value::as_bool)
                    .unwrap_or(false)
                    || title
                        .as_deref()
                        .is_some_and(is_known_harness_injected_user_turn_text);
                push_preview(
                    &mut fold,
                    "user",
                    record
                        .get("message")
                        .and_then(Value::as_object)
                        .and_then(|message| message.get("content")),
                    record.get("timestamp"),
                );
                if let Some(title) = title {
                    if is_meta {
                        if fold.meta_title.is_none() {
                            fold.meta_title = Some(title);
                        }
                    } else if fold.first_user_title.is_none() {
                        fold.first_user_title = Some(title);
                    }
                }
            }
            Some("assistant") => {
                fold.message_count += 1;
                let message = record.get("message").and_then(Value::as_object);
                push_preview(
                    &mut fold,
                    "assistant",
                    message.and_then(|message| message.get("content")),
                    record.get("timestamp"),
                );
                if let Some(model) =
                    message.and_then(|message| extract_string(message.get("model")))
                {
                    fold.model = Some(model.to_string());
                }
                fold.total_tokens +=
                    claude_usage_total(message.and_then(|message| message.get("usage")));
            }
            _ => {}
        }
    }

    fold
}

fn update_timeline(fold: &mut SessionFold, timestamp: Option<&Value>) {
    let Some(raw) = extract_string(timestamp) else {
        return;
    };
    let Some(parsed) = parse_timestamp_ms(raw) else {
        return;
    };
    if fold
        .created_at
        .as_ref()
        .is_none_or(|(current, _)| parsed < *current)
    {
        fold.created_at = Some((parsed, raw.to_string()));
    }
    if fold
        .updated_at
        .as_ref()
        .is_none_or(|(current, _)| parsed >= *current)
    {
        fold.updated_at = Some((parsed, raw.to_string()));
        fold.latest_timestamp_ms = parsed;
    }
}

fn update_location(fold: &mut SessionFold, record: &serde_json::Map<String, Value>) {
    if fold.cwd.is_none() {
        if let Some(cwd) = extract_string(record.get("cwd")) {
            fold.cwd = Some(cwd.to_string());
        }
    }
    let parsed = match extract_string(record.get("timestamp")) {
        Some(timestamp) => match parse_timestamp_ms(timestamp) {
            Some(parsed) => parsed,
            None => return,
        },
        None => fold.latest_timestamp_ms,
    };
    if parsed < fold.latest_timestamp_ms {
        return;
    }
    if let Some(branch) = extract_string(record.get("gitBranch")) {
        fold.branch = Some(branch.to_string());
    }
}

fn push_preview(
    fold: &mut SessionFold,
    role: &'static str,
    content: Option<&Value>,
    timestamp: Option<&Value>,
) {
    let Some(text) = extract_preview_content_text(content) else {
        return;
    };
    if fold.preview_messages.len() >= PREVIEW_MESSAGE_LIMIT {
        fold.preview_messages.remove(0);
        fold.preview_messages_truncated = true;
    }
    fold.preview_messages.push(PreviewMessage {
        role,
        text,
        timestamp: timestamp_iso(timestamp),
    });
}

/// The transcript's own title chain, shared by the scanner row builder (which
/// appends a generated fallback) and [`read_claude_title`] (which does not).
fn extracted_title(fold: &SessionFold) -> Option<String> {
    fold.custom_title
        .clone()
        .or_else(|| fold.ai_title.clone())
        .or_else(|| fold.first_user_title.clone())
        .or_else(|| fold.meta_title.clone())
}

fn build_row(path: &Path, modified_at: &str, fold: SessionFold) -> Value {
    let file_path = path.to_string_lossy().into_owned();
    let session_id = fold.session_id.clone();
    let id = format!("local:claude:{session_id}:{file_path}");
    let resume_command = resume_command(fold.cwd.as_deref(), &session_id);
    let subagent_transcript_count = count_subagent_transcripts(path);
    let title = extracted_title(&fold).unwrap_or_else(|| generated_session_title(&session_id));
    let preview_messages: Vec<Value> = fold
        .preview_messages
        .iter()
        .map(|message| {
            json!({
                "role": message.role,
                "text": message.text,
                "timestamp": message.timestamp,
            })
        })
        .collect();

    let mut row = json!({
        "id": id,
        "executionHostId": "local",
        "agent": "claude",
        "sessionId": session_id,
        "title": title,
        "cwd": fold.cwd,
        "branch": fold.branch,
        "model": fold.model,
        "filePath": file_path,
        "codexHome": Value::Null,
        "createdAt": fold.created_at.map(|(_, raw)| raw),
        "updatedAt": fold.updated_at.map(|(_, raw)| raw),
        "modifiedAt": modified_at,
        "messageCount": fold.message_count,
        "totalTokens": fold.total_tokens,
        "previewMessages": preview_messages,
        "queuedMessageCount": fold.queued_message_count,
        "subagentTranscriptCount": subagent_transcript_count,
        "resumeCommand": resume_command,
        "subagent": Value::Null,
    });
    if fold.preview_messages_truncated {
        row["previewMessagesTruncated"] = Value::Bool(true);
    }
    if let Some(last_user_prompt) = fold.last_user_prompt {
        row["lastUserPrompt"] = Value::String(last_user_prompt);
    }
    row
}

fn generated_session_title(session_id: &str) -> String {
    format!("Claude {}", session_id.chars().take(8).collect::<String>())
}

fn resume_command(cwd: Option<&str>, session_id: &str) -> String {
    let resume = format!("claude --resume {}", quote_posix(session_id));
    match cwd.map(str::trim).filter(|cwd| !cwd.is_empty()) {
        Some(cwd) => format!("cd {} && {resume}", quote_posix(cwd)),
        None => resume,
    }
}

pub(crate) fn quote_posix(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

fn count_subagent_transcripts(transcript_path: &Path) -> u64 {
    let (Some(stem), Some(parent)) = (transcript_path.file_stem(), transcript_path.parent()) else {
        return 0;
    };
    let Ok(entries) = fs::read_dir(parent.join(stem).join("subagents")) else {
        return 0;
    };
    entries
        .filter_map(Result::ok)
        .filter(|entry| {
            entry
                .file_type()
                .map(|kind| kind.is_file())
                .unwrap_or(false)
                && is_subagent_transcript_name(&entry.file_name().to_string_lossy())
        })
        .count() as u64
}

fn is_subagent_transcript_name(name: &str) -> bool {
    name.starts_with("agent-")
        && Path::new(name)
            .extension()
            .is_some_and(|extension| extension.to_string_lossy().eq_ignore_ascii_case("jsonl"))
}

fn session_id_from_file_name(path: &Path) -> String {
    let stem = path
        .file_stem()
        .map(|stem| stem.to_string_lossy().into_owned())
        .unwrap_or_default();
    uuid_suffix(&stem).unwrap_or(stem)
}

fn uuid_suffix(value: &str) -> Option<String> {
    if value.len() < 36 {
        return None;
    }
    let candidate = value.get(value.len() - 36..)?;
    let bytes = candidate.as_bytes();
    let hex_at = |index: usize| bytes[index].is_ascii_hexdigit();
    let valid = (0..8).all(hex_at)
        && bytes[8] == b'-'
        && (9..13).all(hex_at)
        && bytes[13] == b'-'
        && (14..18).all(hex_at)
        && bytes[18] == b'-'
        && (19..23).all(hex_at)
        && bytes[23] == b'-'
        && (24..36).all(hex_at);
    valid.then(|| candidate.to_string())
}

pub(crate) fn extract_string(value: Option<&Value>) -> Option<&str> {
    value
        .and_then(Value::as_str)
        .map(str::trim)
        .filter(|text| !text.is_empty())
}

pub(crate) fn timestamp_iso(value: Option<&Value>) -> Option<String> {
    match value {
        Some(Value::String(raw)) => {
            let trimmed = raw.trim();
            (!trimmed.is_empty()).then(|| trimmed.to_string())
        }
        Some(Value::Number(number)) => number
            .as_i64()
            .filter(|millis| *millis > 0)
            .map(|millis| system_time_to_iso(UNIX_EPOCH + Duration::from_millis(millis as u64))),
        _ => None,
    }
}

fn extract_message_text(message: Option<&Value>) -> Option<String> {
    normalize_content_text(
        message
            .and_then(Value::as_object)
            .and_then(|message| message.get("content")),
        TITLE_TEXT_LIMIT,
    )
}

fn extract_preview_content_text(content: Option<&Value>) -> Option<String> {
    normalize_content_text(content, PREVIEW_TEXT_LIMIT)
}

pub(crate) fn normalize_title_text(value: &str) -> Option<String> {
    let mut builder = TextBuilder::new(TITLE_TEXT_LIMIT);
    append_normalized_string(
        &mut builder,
        &value.encode_utf16().collect::<Vec<u16>>(),
        None,
    );
    finalize_normalized_text(builder)
}

pub(crate) fn normalize_content_text(value: Option<&Value>, limit: usize) -> Option<String> {
    match value {
        Some(Value::String(text)) => {
            let mut builder = TextBuilder::new(limit);
            append_normalized_string(
                &mut builder,
                &text.encode_utf16().collect::<Vec<u16>>(),
                None,
            );
            finalize_normalized_text(builder)
        }
        Some(Value::Array(items)) => {
            let mut builder = TextBuilder::new(limit);
            for item in items {
                let Some(text) = content_item_text(item) else {
                    continue;
                };
                if !builder.text.is_empty() {
                    builder.pending_space = true;
                }
                append_normalized_string(
                    &mut builder,
                    &text.encode_utf16().collect::<Vec<u16>>(),
                    None,
                );
                if builder.truncated {
                    break;
                }
            }
            finalize_normalized_text(builder)
        }
        _ => None,
    }
}

fn content_item_text(item: &Value) -> Option<String> {
    if let Some(text) = item.as_str() {
        return Some(text.to_string());
    }
    let record = item.as_object()?;
    non_blank_string(record.get("text"))
        .or_else(|| non_blank_string(record.get("content")))
        .map(str::to_string)
}

fn non_blank_string(value: Option<&Value>) -> Option<&str> {
    let text = value?.as_str()?;
    has_non_whitespace(text, FIELD_BLANK_SCAN_LIMIT).then_some(text)
}

fn has_non_whitespace(value: &str, max_scan_length: usize) -> bool {
    let units: Vec<u16> = value.encode_utf16().collect();
    let scan_limit = units.len().min(max_scan_length);
    if units[..scan_limit]
        .iter()
        .any(|code| !is_whitespace_code(*code))
    {
        return true;
    }
    units.len() > scan_limit
}

fn claude_usage_total(usage: Option<&Value>) -> u64 {
    let Some(usage) = usage.and_then(Value::as_object) else {
        return 0;
    };
    number_value(usage.get("input_tokens"))
        + number_value(usage.get("output_tokens"))
        + number_value(usage.get("cache_read_input_tokens"))
        + number_value(usage.get("cache_creation_input_tokens"))
}

pub(crate) fn number_value(value: Option<&Value>) -> u64 {
    let Some(value) = value else {
        return 0;
    };
    if let Some(integer) = value.as_u64() {
        return integer;
    }
    value
        .as_f64()
        .filter(|float| float.is_finite() && *float >= 0.0)
        .map(|float| float as u64)
        .unwrap_or(0)
}

fn is_known_harness_injected_user_turn_text(text: &str) -> bool {
    let normalized = normalized_harness_turn_head(text);
    if normalized.is_empty() {
        return false;
    }
    if let Some(tag_name) = leading_tag_name(&normalized) {
        if KNOWN_HARNESS_TAG_NAMES.contains(&tag_name.as_str()) {
            return true;
        }
    }
    HARNESS_INJECTED_TURN_PREFIXES
        .iter()
        .any(|prefix| normalized.starts_with(prefix))
}

fn normalized_harness_turn_head(text: &str) -> String {
    let units: Vec<u16> = text.encode_utf16().collect();
    let mut start = 0;
    let ws_scan_end = units.len().min(HARNESS_CLASSIFY_LEADING_WS_LIMIT);
    while start < ws_scan_end && is_ascii_whitespace_code(units[start]) {
        start += 1;
    }
    if start >= units.len() {
        return String::new();
    }
    let head_end = units.len().min(start + HARNESS_CLASSIFY_HEAD_LIMIT);
    String::from_utf16_lossy(&units[start..head_end]).to_lowercase()
}

fn leading_tag_name(value: &str) -> Option<String> {
    let rest = value.strip_prefix('<')?;
    let mut name_len = 0;
    for (index, ch) in rest.char_indices() {
        if index == 0 && !ch.is_ascii_lowercase() {
            return None;
        }
        if !ch.is_ascii_lowercase() && !ch.is_ascii_digit() && ch != '-' {
            return if ch.is_whitespace() || ch == '>' {
                Some(rest[..index].to_string())
            } else {
                None
            };
        }
        name_len = index + ch.len_utf8();
    }
    Some(rest[..name_len].to_string())
}

fn is_ascii_whitespace_code(code: u16) -> bool {
    matches!(code, 32 | 9 | 10 | 13 | 12)
}

struct TextBuilder {
    limit: usize,
    text: Vec<u16>,
    pending_space: bool,
    truncated: bool,
}

impl TextBuilder {
    fn new(limit: usize) -> Self {
        TextBuilder {
            limit,
            text: Vec::new(),
            pending_space: false,
            truncated: false,
        }
    }
}

fn append_normalized_string(
    builder: &mut TextBuilder,
    value: &[u16],
    max_scan_length: Option<usize>,
) {
    let scan_end = max_scan_length.map_or(value.len(), |max| max.min(value.len()));
    let mut index = 0;
    while index < scan_end && !builder.truncated {
        if let Some(hidden_end) = hidden_text_block_end(value, index) {
            if !builder.text.is_empty() {
                builder.pending_space = true;
            }
            index = hidden_end.min(scan_end);
            continue;
        }

        let code = value[index];
        if is_whitespace_code(code) {
            if !builder.text.is_empty() {
                builder.pending_space = true;
            }
            index += 1;
            continue;
        }

        if builder.pending_space {
            append_visible_text(builder, &[b' ' as u16]);
            builder.pending_space = false;
            if builder.truncated {
                break;
            }
        }

        let char_length = code_point_length(value, index);
        if index + char_length > scan_end {
            break;
        }
        append_visible_text(builder, &value[index..index + char_length]);
        index += char_length;
    }
    if !builder.truncated && scan_end < value.len() && !builder.text.is_empty() {
        builder.truncated = true;
    }
}

fn append_visible_text(builder: &mut TextBuilder, value: &[u16]) {
    builder.text.extend_from_slice(value);
    builder.truncated = builder.text.len() > builder.limit;
}

fn hidden_text_block_end(value: &[u16], index: usize) -> Option<usize> {
    if value.get(index).copied() != Some(b'<' as u16) {
        return None;
    }
    for (name, close_tag) in HIDDEN_TEXT_BLOCKS {
        let name_start = index + 1;
        if !starts_with_ignore_case(value, name, name_start) {
            continue;
        }
        let after_name = name_start + name.len();
        let boundary = value.get(after_name).copied();
        if !boundary.is_none_or(is_tag_boundary) {
            continue;
        }
        let Some(open_end) = tag_end_index(value, after_name) else {
            return Some(value.len());
        };
        let close_start = index_of_ignore_case(
            value,
            close_tag,
            open_end + 1,
            open_end + 1 + HIDDEN_BLOCK_CLOSE_SCAN_LIMIT,
        );
        return Some(match close_start {
            Some(start) => start + close_tag.len(),
            None => value.len(),
        });
    }
    None
}

fn tag_end_index(value: &[u16], from_index: usize) -> Option<usize> {
    let scan_end = value
        .len()
        .min(from_index + HIDDEN_BLOCK_OPEN_TAG_SCAN_LIMIT);
    (from_index..scan_end).find(|index| value[*index] == b'>' as u16)
}

fn index_of_ignore_case(
    value: &[u16],
    search: &str,
    from_index: usize,
    end_index: usize,
) -> Option<usize> {
    let search_length = search.encode_utf16().count();
    let last_start = value
        .len()
        .min(end_index)
        .min(value.len().saturating_sub(search_length) + 1);
    (from_index..last_start).find(|index| starts_with_ignore_case(value, search, *index))
}

fn starts_with_ignore_case(value: &[u16], search: &str, from_index: usize) -> bool {
    let search: Vec<u16> = search.encode_utf16().collect();
    if from_index + search.len() > value.len() {
        return false;
    }
    search
        .iter()
        .enumerate()
        .all(|(offset, unit)| to_lower_ascii(value[from_index + offset]) == to_lower_ascii(*unit))
}

fn to_lower_ascii(code: u16) -> u16 {
    if (65..=90).contains(&code) {
        code + 32
    } else {
        code
    }
}

fn is_tag_boundary(code: u16) -> bool {
    code == b'>' as u16 || is_whitespace_code(code)
}

fn is_word_boundary(code: Option<u16>) -> bool {
    code.is_none_or(|code| !is_word_code(code))
}

fn is_word_code(code: u16) -> bool {
    (48..=57).contains(&code)
        || (65..=90).contains(&code)
        || (97..=122).contains(&code)
        || code == b'_' as u16
}

fn is_whitespace_code(code: u16) -> bool {
    code == 32
        || (9..=13).contains(&code)
        || code == 160
        || code == 5760
        || (8192..=8202).contains(&code)
        || code == 8232
        || code == 8233
        || code == 8239
        || code == 8287
        || code == 12288
        || code == 65279
}

fn code_point_length(value: &[u16], index: usize) -> usize {
    let code = value[index];
    if (0xd800..=0xdbff).contains(&code)
        && value
            .get(index + 1)
            .is_some_and(|next| (0xdc00..=0xdfff).contains(next))
    {
        2
    } else {
        1
    }
}

fn finalize_normalized_text(builder: TextBuilder) -> Option<String> {
    if builder.text.is_empty() {
        return None;
    }
    let text = String::from_utf16(&builder.text)
        .unwrap_or_else(|_| String::from_utf16_lossy(&builder.text));
    if is_suppressed_context_prefix(&text) {
        return None;
    }
    if builder.truncated {
        Some(truncate_with_ellipsis(&text, builder.limit))
    } else {
        Some(text)
    }
}

fn is_suppressed_context_prefix(value: &str) -> bool {
    let units: Vec<u16> = value.encode_utf16().collect();
    let agents_length = AGENTS_INSTRUCTIONS_PREFIX.encode_utf16().count();
    if starts_with_ignore_case(&units, AGENTS_INSTRUCTIONS_PREFIX, 0)
        && is_word_boundary(units.get(agents_length).copied())
    {
        return true;
    }
    starts_with_ignore_case(&units, XML_INSTRUCTIONS_PREFIX, 0)
}

fn truncate_with_ellipsis(value: &str, limit: usize) -> String {
    let slice_limit = limit.saturating_sub(ELLIPSIS.len());
    format!("{}{ELLIPSIS}", slice_at_code_unit_limit(value, slice_limit))
}

fn slice_at_code_unit_limit(value: &str, limit: usize) -> String {
    let units: Vec<u16> = value.encode_utf16().collect();
    if units.len() <= limit {
        return value.to_string();
    }
    let mut end = limit;
    if end > 0 && (0xd800..=0xdbff).contains(&units[end - 1]) {
        end -= 1;
    }
    String::from_utf16_lossy(&units[..end])
}

pub(crate) fn parse_timestamp_ms(value: &str) -> Option<i64> {
    let bytes = value.as_bytes();
    if bytes.len() < 10 {
        return None;
    }
    let year = parse_digits(bytes, 0, 4)?;
    if bytes[4] != b'-' {
        return None;
    }
    let month = parse_digits(bytes, 5, 2)?;
    if bytes[7] != b'-' {
        return None;
    }
    let day = parse_digits(bytes, 8, 2)?;
    if !(1..=12).contains(&month) || day < 1 || day > days_in_month(year, month as u32) {
        return None;
    }

    let mut index = 10;
    let (mut hour, mut minute, mut second, mut millis) = (0i64, 0i64, 0i64, 0i64);
    let mut offset_seconds = 0i64;
    if matches!(bytes.get(index), Some(b'T') | Some(b't')) {
        index += 1;
        hour = parse_digits(bytes, index, 2)?;
        if bytes.get(index + 2) != Some(&b':') {
            return None;
        }
        minute = parse_digits(bytes, index + 3, 2)?;
        index += 5;
        if bytes.get(index) == Some(&b':') {
            second = parse_digits(bytes, index + 1, 2)?;
            index += 3;
        }
        if bytes.get(index) == Some(&b'.') {
            index += 1;
            let fraction_start = index;
            while bytes.get(index).is_some_and(u8::is_ascii_digit) {
                index += 1;
            }
            if index == fraction_start {
                return None;
            }
            let fraction_end = index.min(fraction_start + 3);
            let fraction = &bytes[fraction_start..fraction_end];
            millis =
                parse_digits(fraction, 0, fraction.len())? * 10i64.pow(3 - fraction.len() as u32);
        }
        match bytes.get(index) {
            Some(b'Z') | Some(b'z') => index += 1,
            Some(sign @ (b'+' | b'-')) => {
                let sign = if *sign == b'-' { -1 } else { 1 };
                let offset_hour = parse_digits(bytes, index + 1, 2)?;
                let colon_offset = bytes.get(index + 3) == Some(&b':');
                let offset_minute = if colon_offset {
                    parse_digits(bytes, index + 4, 2)?
                } else {
                    parse_digits(bytes, index + 3, 2)?
                };
                offset_seconds = sign * (offset_hour * 3600 + offset_minute * 60);
                index += if colon_offset { 6 } else { 5 };
            }
            None => {}
            _ => return None,
        }
    }
    if index != bytes.len() {
        return None;
    }
    if hour > 23 || minute > 59 || second > 59 {
        return None;
    }

    let days = days_from_civil(year, month as u32, day as u32);
    Some((days * 86_400 + hour * 3600 + minute * 60 + second - offset_seconds) * 1000 + millis)
}

fn parse_digits(bytes: &[u8], start: usize, length: usize) -> Option<i64> {
    let slice = bytes.get(start..start + length)?;
    if !slice.iter().all(u8::is_ascii_digit) {
        return None;
    }
    Some(
        slice
            .iter()
            .fold(0i64, |total, byte| total * 10 + i64::from(byte - b'0')),
    )
}

fn days_in_month(year: i64, month: u32) -> i64 {
    match month {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        2 => {
            if is_leap_year(year) {
                29
            } else {
                28
            }
        }
        _ => 0,
    }
}

fn is_leap_year(year: i64) -> bool {
    year % 4 == 0 && (year % 100 != 0 || year % 400 == 0)
}

pub(crate) fn system_time_to_iso(time: SystemTime) -> String {
    let duration = time.duration_since(UNIX_EPOCH).unwrap_or_default();
    let seconds = duration.as_secs() as i64;
    let millis = duration.subsec_millis();
    let days = seconds.div_euclid(86_400);
    let seconds_of_day = seconds.rem_euclid(86_400);
    let (year, month, day) = civil_from_days(days);
    format!(
        "{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}.{millis:03}Z",
        seconds_of_day / 3600,
        (seconds_of_day % 3600) / 60,
        seconds_of_day % 60
    )
}

fn civil_from_days(days: i64) -> (i64, u32, u32) {
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let year = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let month = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (year + if month <= 2 { 1 } else { 0 }, month, day)
}

fn days_from_civil(year: i64, month: u32, day: u32) -> i64 {
    let year = if month <= 2 { year - 1 } else { year };
    let era = if year >= 0 { year } else { year - 399 } / 400;
    let yoe = year - era * 400;
    let mp = if month > 2 { month - 3 } else { month + 9 } as i64;
    let doy = (153 * mp + 2) / 5 + day as i64 - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

